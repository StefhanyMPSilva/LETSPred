@click.group()
def cli():
    """
    LETSPred - ML Pipeline for compound activity prediction.
 
    Classifies chemical compounds as active or inactive against a biological
    target using molecular descriptors (DataWarrior) and docking scores (GOLD).
 
    \b
    Available commands:
        create-model    Train new ML models from actives/decoys datasets
        prebuildmodel   Predict using a pre-built dataset (no training required)
        usermodel       Predict using your own previously trained model
 
   \b
    Typical workflow:

    1. Train a new model from your actives and decoys:
        python cli.py create-model \\
            --actives-datawarrior actives.txt \\
            --decoys-datawarrior  decoys.txt  \\
            --actives-consolidated actives.csv \\
            --decoys-consolidated  decoys.csv \\
            --output EGFR

    2. Predict new compounds using a pre-built dataset:
        python cli.py prebuildmodel \\
            --build dataset1 \\
            --actives-datawarrior actives.txt \\
            --actives-consolidated actives.csv \\
            --output test1
            --models ALL

    3. Predict new compounds using your own trained model:
        python cli.py usermodel \\
            --run EGFR-20260101_1200 \\
            --actives-datawarrior actives.txt \\
            --actives-consolidated actives.csv \\
            --output test1
            --models ALL

    \b
    Output directories:
        usermodel/              Trained models generated by create-model
        prebuildmodel/          Pre-built datasets provided with LETSpred
        output_predictions/     Results from prebuildmodel and usermodel

    \b
    Run any command with --help for detailed usage:
        python cli.py create-model --help
        python cli.py prebuildmodel --help
        python cli.py usermodel --help
    """
    pass

@cli.command('create-model')
@click.option(
    "--actives-datawarrior", "actives_dw_path", required=True,
    help=("Path to the DataWarrior descriptor file for ACTIVE compounds (actives_datawarrior.txt). "
          " Generated by DataWarrior using the active ligands as input."),
)
@click.option(
    "--decoys-datawarrior", "decoys_dw_path", required=True,
    help=( "Path to the DataWarrior descriptor file for DECOY compounds (decoys_datawarrior.txt). "
           "Generated by DataWarrior using the decoy/inactive molecules as input."),
)
@click.option(
    "--actives-consolidated", "actives_cons_path",
    required=True,
    help=("Path to the consolidated CSV for ACTIVE compounds(active_consolidated.csv)." 
          "Must contain at minimum a SMILES column and a compound identifier."),
)
@click.option(
    "--decoys-consolidated", "decoys_cons_path",
    required=True,
    help=( "Path to the consolidated CSV for DECOY compounds (decoys_consolidated.csv)." 
           "Same format as --actives-consolidated."),
)
@click.option(
    "--output", "output_prefix",
    required=True,
    help=( "Prefix used for the output run folder and all generated files (models, metrics, data). "
           "Example: 'EGFR' produces output/EGFR-YYYYMMDD_HHMM/."),
)
def create_model(actives_dw_path, decoys_dw_path, actives_cons_path, decoys_cons_path, output_prefix):
    """
    Train ML models from active and decoy compound datasets.
 
    The pipeline runs the following steps automatically:
 
    \b
      1. Prepare files   — merge and label actives/decoys
      2. Pre-treatment   — remove low-variance and correlated features
      3. Normalization   — scale features; saves scaler for later use
      4. Train models    — cross-validated training of multiple classifiers
      5. App. domain     — detect outliers via distance-based analysis
      6. Predict         — consensus prediction on non-outlier compounds
 
    \b
    Output layout (under output/<PREFIX>-<TIMESTAMP>/):
      models/      — trained model .pkl files, scaler, train/test splits (.npz) and run config
      metrics/     — model_metrics.csv with cross-validation scores
      domain_app/  — distance.csv, outlier analysis CSVs and applicability domain plot (.png)
      predicts/    — new_with_consensus.csv with final consensus predictions
      temp/        — intermediate CSVs and copied input files
 
    \b
    Example:
      python main.py create-model \\
        --actives-datawarrior  example_files/actives_datawarrior.txt \\
        --decoys-datawarrior   example_files/decoys_datawarrior.txt  \\
        --actives-consolidated example_files/active_consolidated.csv \\
        --decoys-consolidated  example_files/decoys_consolidated.csv \\
        --output new_test
    """

    click.echo(f"Starting pipeline | prefix: {output_prefix}")
    
    output_root = os.path.join(os.path.dirname(os.path.abspath(__file__)), "usermodel")
    os.makedirs(output_root, exist_ok=True)

    timestamp = datetime.now().strftime("%Y%m%d_%H%M")
    run_name = f"{output_prefix}-{timestamp}"
    base_dir = os.path.join(output_root, run_name)

    temp_dir = os.path.join(base_dir, "temp")
    models_dir = os.path.join(base_dir, "models")
    metrics_dir = os.path.join(base_dir, "metrics")
    predict_dir = os.path.join(base_dir, "predicts")
    domain_dir = os.path.join(base_dir, "domain_app")
    train_dir = os.path.join(base_dir, "artifacts")

    for directory in [temp_dir, models_dir, metrics_dir, predict_dir, domain_dir, train_dir]:
        os.makedirs(directory, exist_ok=True)
    
    # Copy input files to temp directory
    shutil.copy(actives_dw_path, os.path.join(temp_dir, 'actives_datawarrior.txt'))
    shutil.copy(decoys_dw_path, os.path.join(temp_dir, 'decoys_datawarrior.txt'))
    shutil.copy(actives_cons_path, os.path.join(temp_dir, 'active_consolidated.csv'))
    shutil.copy(decoys_cons_path, os.path.join(temp_dir, 'decoys_consolidated.csv'))

    # Change to temp directory
    original_dir = os.getcwd()
    os.chdir(temp_dir)
    
    # Import processing modules
    from core import (
        prepare_files, 
        pre_treatment, 
        normalization, 
        train_models,
        predict_compounds,
        domain_applicability,
    )
    
    try:
        # --------------------------------------------------------- step 1
        click.echo("[1/6] Preparing files...")
        df_final = prepare_files.process()
        df_final.to_csv('df_final.csv', index=False)
        
        # --------------------------------------------------------- step 2
        click.echo("[2/6] Pre-treating data...")
        df_var_final = pre_treatment.process('df_final.csv')
        df_var_final.to_csv('df_var_final.csv', index=False)
        
        # --------------------------------------------------------- step 3
        click.echo("[3/6] Normalizing data...")
        df_reduced, df_reduced_wname, scaler, train_columns, model_columns, to_drop = normalization.process('df_var_final.csv')
        df_reduced.to_csv('df_reduced.csv', index=False)
        df_reduced_wname.to_csv('df_reduced_wname.csv', index=False)

        # Save scaler
        scaler_path = os.path.join(train_dir, "scaler.pkl")
        with open(scaler_path, 'wb') as f:
            pickle.dump(scaler, f)

        train_columns_path = os.path.join(train_dir, "train_columns.pkl")
        with open(train_columns_path, 'wb') as f:
            pickle.dump(train_columns, f)

        model_columns_path = os.path.join(train_dir, "model_columns.pkl")
        with open(model_columns_path, 'wb') as f:
            pickle.dump(model_columns, f)

        columns_removed_path = os.path.join(train_dir, "columns_removed.pkl")
        with open(columns_removed_path, 'wb') as f:
            pickle.dump(list(to_drop), f)
        
        # --------------------------------------------------------- step 4
        click.echo("[4/6] Training models...")
        models, metrics, data_splits, results_df = train_models.process('df_reduced.csv')
        results_df.to_csv(os.path.join(models_dir, 'best_train_model.csv'), index=False)
        
        # Save models
        for model_name, model in models.items():
            model_path = os.path.join(models_dir, f"{model_name}_model.pkl")
            with open(model_path, 'wb') as f:
                pickle.dump(model, f)
        
        # Save metrics
        metrics.to_csv(os.path.join(metrics_dir, "model_metrics.csv"), index=False)
        
        # Save data splits
        np.savez(os.path.join(train_dir, "train_test_data.npz"), 
                 X_train=data_splits['X_train'], 
                 X_test=data_splits['X_test'], 
                 y_train=data_splits['y_train'], 
                 y_test=data_splits['y_test'])
        
        X_train = data_splits['X_train']
        
        # --------------------------------------------------------- step 5
        click.echo("[5/6] Computing applicability domain...")
        distance_df, plot_scatter, df_cat_sem_out, df_externo_distance = domain_applicability.process(df_reduced_wname, X_train)
        distance_df.to_csv(os.path.join(domain_dir, 'distance.csv'), index=False)
        df_cat_sem_out.to_csv(os.path.join(domain_dir,'data_non_outliers.csv'), index=False)
        df_externo_distance.to_csv(os.path.join(domain_dir,'df_externo_with_distance.csv'), index=False)

        with open(os.path.join(domain_dir, "domain_applicability.png"), "wb") as f:
             f.write(plot_scatter.getbuffer())


        # --------------------------------------------------------- step 6
        click.echo("[6/6] Predicting compounds...")
        df_pred = predict_compounds.process(df_cat_sem_out, models_dir)
        df_pred.to_csv(os.path.join(predict_dir, 'new_with_consensus.csv'), index=False)
        # =====
        
        # Save config info
        config_info = {
            'created_at': timestamp,
            'run_dir': base_dir,
            'actives_datawarrior': actives_dw_path,
            'decoys_datawarrior': decoys_dw_path,
            'actives_consolidated': actives_cons_path,
            'decoys_consolidated': decoys_cons_path,
            'output_prefix': output_prefix
        }
        
        config_path = os.path.join(output_root, run_name, "config.pkl")
        with open(config_path, 'wb') as f:
            pickle.dump(config_info, f)
            
        click.echo(f"Model created and saved in: {base_dir}")
        
    except Exception as e:
        click.echo(f"Error: {e}", err=True)
        raise
    
    finally:
        os.chdir(original_dir)

# =============== prebuildmodel ===============
@cli.command('prebuildmodel')
@click.option(
    "--build", "build_name", required=True,
    help="Name of the pre-built dataset folder inside prebuild/. Example: 'dataset1'",
)
@click.option(
    "--actives-datawarrior", "actives_dw_path", required=True,
    help="Path to the DataWarrior descriptor file for ACTIVE compounds.",
)
@click.option(
    "--actives-consolidated", "actives_cons_path", required=True,
    help="Path to the consolidated CSV for ACTIVE compounds.",
)
@click.option(
    "--output", "output_prefix", required=True,
    help="Prefix for the output folder. Example: 'test1' produces output/test1-YYYYMMDD_HHMM/",
)
@click.option(
    "--models", "selected_models", default="ALL", show_default=True,
    help="Models to use. Options: ALL, or comma-separated list: DT,RF,SVM,LR,NB,XGB. Example: --models RF,XGB,SVM"
)

def prebuilmodel(build_name, actives_dw_path, actives_cons_path, output_prefix, selected_models):
    """
    Predict compound activity using a pre-built model.

    Loads a pre-trained pipeline from the prebuild/ directory and applies it
    to new active compounds, skipping the training step entirely.

    \b
    The selected --build folder must contain:
      artifacts/   — scaler.pkl, train_columns.pkl, model_columns.pkl, columns_removed.pkl
      models/      — trained model .pkl files

    \b
    Example:
      python cli.py prebuildmodel \ \\
        --build dataset1 \ \\
        --actives-datawarrior  example_files/actives_datawarrior.txt \ \\
        --actives-consolidated example_files/active_consolidated.csv \ \\
        --output test1 \ \\
        --models ALL

    \b 
    Others Examples models:
    python cli.py prebuildmodel --build dataset1 ... --models ALL
    
    python cli.py prebuildmodel --build dataset1 ... --models RF,XGB,SVM
    (Note: no spaces between the commas - RF,XGB,SVM,...)

    python cli.py prebuildmodel --build dataset1 ... --models DT
    """

    cli_root = os.path.dirname(os.path.abspath(__file__))
    prebuild_root = os.path.join(cli_root, "prebuildmodel")
    build_dir = os.path.join(prebuild_root, build_name)

    if not os.path.isdir(build_dir):
        available = [d for d in os.listdir(prebuild_root) if os.path.isdir(os.path.join(prebuild_root, d))] if os.path.isdir(prebuild_root) else []
        click.echo(f"Error: pre-built dataset '{build_name}' not found in {prebuild_root}", err=True)
        if available:
            click.echo(f"Available datasets: {', '.join(available)}", err=True)
        raise SystemExit(1)

    artifacts_dir = os.path.join(build_dir, "artifacts")
    models_dir    = os.path.join(build_dir, "models")

    # Validate required files
    required_artifacts = ["scaler.pkl", "train_columns.pkl", "model_columns.pkl", "columns_removed.pkl"]
    missing = [f for f in required_artifacts if not os.path.exists(os.path.join(artifacts_dir, f))]
    if missing:
        click.echo(f"Error: missing artifact files in {artifacts_dir}: {missing}", err=True)
        raise SystemExit(1)

    click.echo(f"Using pre-built dataset: {build_name}")

    # Set up output directory 
    output_root = os.path.join(cli_root, "output_predictions")
    os.makedirs(output_root, exist_ok=True)

    timestamp = datetime.now().strftime("%Y%m%d_%H%M")
    run_name = f"{output_prefix}-{timestamp}"
    base_dir = os.path.join(output_root, run_name)

    temp_dir = os.path.join(base_dir, "temp")
    predict_dir = os.path.join(base_dir, "predicts")
    domain_dir = os.path.join(base_dir, "domain_app")

    for directory in [temp_dir, predict_dir, domain_dir]:
        os.makedirs(directory, exist_ok=True)

    # Copy input files to temp
    shutil.copy(actives_dw_path,  os.path.join(temp_dir, 'actives_datawarrior.txt'))
    shutil.copy(actives_cons_path, os.path.join(temp_dir, 'active_consolidated.csv'))

    original_dir = os.getcwd()
    os.chdir(temp_dir)

    from core import (
        prepare_files_predict,
        pre_treatment_predict,
        predict_compounds,
        domain_applicability,
    )

    # Filtrando modelos
    VALID_MODELS = {'LR', 'NB', 'DT', 'RF', 'SVM', 'XGB'}

    if selected_models.upper() == 'ALL':
        models_to_use = VALID_MODELS
    else:
        models_to_use = {m.strip().upper() for m in selected_models.split(',')}
        invalid = models_to_use - VALID_MODELS
        if invalid:
            click.echo(f"Error: invalid models: {invalid}. Valid options: {VALID_MODELS}", err=True)
            raise SystemExit(1)

    click.echo(f"Using models: {', '.join(sorted(models_to_use))}")

    try:
        click.echo("[1/4] Loading pre-built artifacts...")
        with open(os.path.join(artifacts_dir, "scaler.pkl"), 'rb') as f:
            scaler = pickle.load(f)
        with open(os.path.join(artifacts_dir, "train_columns.pkl"), 'rb') as f:
            train_columns = pickle.load(f)
        with open(os.path.join(artifacts_dir, "model_columns.pkl"), 'rb') as f:
            model_columns = pickle.load(f)

        # Carregar dados de treino originais para calcular dominio de aplicabilidade
        data_splits = np.load(os.path.join(artifacts_dir, "train_test_data.npz"))
        X_train = pd.DataFrame(data_splits['X_train'], columns=model_columns)

        click.echo("[2/4] Preparing actives data...")
        df_final = prepare_files_predict.process()
        df_final.to_csv('df_final.csv', index=False)

        df_var_final = pre_treatment_predict.process('df_final.csv', train_columns)
        df_var_final.to_csv('df_var_final.csv', index=False)

        click.echo("[3/4] Applying normalization with pre-built scaler...")
        df = pd.read_csv('df_var_final.csv')
        df_name = df.pop('name')
        df_activity = df.pop('activity') if 'activity' in df.columns else None

        # Alinhando colunas - zerando colunas faltantes, removendo extras e mantendo a ordem das colunas
        X_new = df.reindex(columns=train_columns, fill_value=0)

        # Normalizando com os dados do scaler - scaler aprendeu com minmax do treino, então aqui é aplicado a mesma escala
        X_norm = pd.DataFrame(scaler.transform(X_new), columns=train_columns)

        # Remoção das mesmas colunas removidas durante o treino na etapa de correlação > 0.5
        X_final = X_norm.reindex(columns=model_columns, fill_value=0)

        if df_activity is not None:
            X_final['activity'] = df_activity.values

        df_reduced_wname = pd.concat(
            [df_name.reset_index(drop=True), X_final.reset_index(drop=True)],
            axis=1
        )

        X_final.to_csv('df_reduced.csv', index=False)
        df_reduced_wname.to_csv('df_reduced_wname.csv', index=False)

        # Load X_train from prebuild for domain applicability
        data_splits = np.load(os.path.join(artifacts_dir, "train_test_data.npz"))
        X_train = pd.DataFrame(data_splits['X_train'], columns=model_columns)

        click.echo("[4/4] Computing applicability domain and predicting...")
        distance_df, plot_scatter, df_cat_sem_out, df_externo_distance = domain_applicability.process(df_reduced_wname, X_train)
        distance_df.to_csv(os.path.join(domain_dir, 'distance.csv'), index=False)
        df_cat_sem_out.to_csv(os.path.join(domain_dir, 'data_non_outliers.csv'), index=False)
        df_externo_distance.to_csv(os.path.join(domain_dir, 'df_externo_with_distance.csv'), index=False)

        with open(os.path.join(domain_dir, "domain_applicability.png"), "wb") as f:
            f.write(plot_scatter.getbuffer())

        # Predict 
        df_pred = predict_compounds.process(df_cat_sem_out, models_dir, models_to_use)
        df_pred = df_pred[df_pred['consensus'] > 0]

        df_pred.to_csv(os.path.join(predict_dir, 'new_with_consensus.csv'), index=False)

        # Save config
        config_info = {
            'created_at': timestamp,
            'run_dir': base_dir,
            'build_name': build_name,
            'actives_datawarrior': actives_dw_path,
            'actives_consolidated': actives_cons_path,
            'output_prefix': output_prefix,
            'mode': 'prebuildmodel'
        }
        with open(os.path.join(base_dir, "config.pkl"), 'wb') as f:
            pickle.dump(config_info, f)

        click.echo(f"Done! Results saved in: {base_dir}")

    except Exception as e:
        click.echo(f"Error: {e}", err=True)
        raise

    finally:
        os.chdir(original_dir)

